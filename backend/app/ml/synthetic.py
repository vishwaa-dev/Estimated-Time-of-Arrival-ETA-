"""Synthetic training data generator.

HONESTY NOTE (per brief §13/§40): there is no historical bulk dataset for this
prototype. The samples below are generated by perturbing plausible operational
states and labelling them with a NOISY version of the deterministic rule
estimator. The model therefore learns the prototype's own heuristics plus
noise — it is "Prototype / synthetic training data" and must never be
presented as learning real railway behaviour.
"""
import random

from app.ml.features import build_vector_from_values

# Peak hours (IST) mirrored from prediction_service
PEAK_HOURS = set(range(5, 10)) | set(range(17, 22))


def _rule_target(vec: list[float], congestion: float) -> float:
    """Standalone copy of the deterministic estimator used ONLY to label
    synthetic samples (documented in prediction_service.predict_additional_delay)."""
    (current_delay, previous_delay, current_speed, average_speed, speed_deviation,
     running_delay, distance_remaining, upcoming_stops, dwell_deviation,
     weather_risk, rainfall, wind_speed, visibility, time_of_day,
     route_slack, recovery_potential) = vec

    expected = max(average_speed - speed_deviation, 20.0)
    slowdown = 0.0
    if current_speed and current_speed > 5 and distance_remaining > 0:
        extra = distance_remaining * (1.0 / current_speed - 1.0 / max(expected, 20.0)) * 60.0
        slowdown = min(max(0.0, extra) * 0.6, 30.0)

    dwell_factor = min(2.0, 1.0 + max(0.0, dwell_deviation) * 0.15 + 0.8 * congestion)
    stops = min(15.0, upcoming_stops * 1.5 * dwell_factor) if upcoming_stops else 0.0
    weather = (weather_risk / 100.0) * min(12.0, 2.0 + distance_remaining / 60.0)
    trend = max(-2.0, min(4.0, 0.5 * (current_delay - previous_delay)))
    peak = 1.5 if int(time_of_day) in PEAK_HOURS else 0.0
    congestion_component = 6.0 * congestion

    total = slowdown + stops + weather + max(0.0, trend) + peak + congestion_component
    if trend < 0:
        total += trend
    return max(0.0, min(60.0, total))


def generate_samples(n: int = 4000, seed: int = 42) -> tuple[list[list[float]], list[float]]:
    rng = random.Random(seed)
    vectors: list[list[float]] = []
    targets: list[float] = []
    for _ in range(n):
        current_delay = rng.uniform(0, 60)
        previous_delay = max(0.0, current_delay + rng.gauss(-1.0, 3.0))
        current_speed = rng.uniform(25, 110)
        average_speed = rng.uniform(35, 75)
        speed_deviation = rng.uniform(-15, 30)  # positive = slower than profile
        distance_remaining = rng.uniform(5, 500)
        upcoming_stops = rng.randint(0, 8)
        dwell_deviation = rng.uniform(-1, 8)
        weather_risk = rng.uniform(0, 100)
        rainfall = max(0.0, (weather_risk - 30) / 10 * rng.uniform(0.5, 1.5)) if weather_risk > 30 else 0.0
        wind_speed = rng.uniform(1, 14)
        visibility = max(0.5, rng.uniform(9, 10) if weather_risk < 60 else rng.uniform(0.8, 6))
        time_of_day = rng.randint(0, 23)
        route_slack = rng.uniform(0, 25)
        recovery_potential = min(route_slack, current_delay)
        congestion = rng.choice([0.0, 0.0, 0.5, 0.9])

        vec = build_vector_from_values(
            current_delay, previous_delay, current_speed, average_speed, speed_deviation,
            rng.uniform(0, current_delay), distance_remaining, upcoming_stops,
            dwell_deviation, weather_risk, rainfall, wind_speed, visibility,
            time_of_day, route_slack, recovery_potential,
        )
        noise = rng.gauss(0.0, 1.5)
        vectors.append(vec)
        targets.append(max(0.0, _rule_target(vec, congestion) + noise))
    return vectors, targets
